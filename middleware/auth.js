// جدار حماية للتحقق من أن المستخدم قام بتسجيل الدخول الفعلي قبل تمرير البيانات له
module.exports = (req, res, next) => {
  if (req.session && req.session.userId) {
    // إذا كان يمتلك جلسة نشطة، اسمح له بالمرور للمسار المطلوب
    return next();
  } else {
    // إذا لم يكن مسجلاً، امنعه فوراً وأرسل رمز خطأ حماية 401
    return res.status(401).json({ error: "غير مصرح لك، يرجى تسجيل الدخول أولاً بالنظام." });
  }
};
